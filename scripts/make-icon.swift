NSBezierPath(roundedRect: NSRect(x: 203, y: 214, width: 106, height: 194), xRadius: 53, yRadius: 53).fill()
NSColor.white.setStroke()
let arc = NSBezierPath()
arc.move(to: NSPoint(x: 164, y: 266))
arc.line(to: NSPoint(x: 164, y: 232))
arc.curve(to: NSPoint(x: 348, y: 232), controlPoint1: NSPoint(x: 164, y: 110), controlPoint2: NSPoint(x: 348, y: 110))
arc.line(to: NSPoint(x: 348, y: 266)); arc.lineWidth = 20; arc.lineCapStyle = .round; arc.stroke()
let stand = NSBezierPath()
stand.move(to: NSPoint(x: 256, y: 141)); stand.line(to: NSPoint(x: 256, y: 102))
stand.move(to: NSPoint(x: 206, y: 100)); stand.line(to: NSPoint(x: 306, y: 100))
stand.lineWidth = 20; stand.lineCapStyle = .round; stand.stroke()
image.unlockFocus()
let bitmap = NSBitmapImageRep(data: image.tiffRepresentation!)!
try bitmap.representation(using: .png, properties: [:])!.write(to: URL(fileURLWithPath: CommandLine.arguments[1]))
